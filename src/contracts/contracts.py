@dataclass
class BaseContract:
    """Base dataclass for all ORION normative data contracts.

    Provides standard metadata, hash computation, HMAC signing, verification,
    dictionary conversion, and validation interface.
    """
    schema_version: str = "1.0.0"
    contract_version: str = "1.0.0"
    contract_id: str = field(default_factory=generate_contract_id)
    timestamp: int = field(default_factory=current_timestamp_ns)
    producer: str = ""
    consumer: str = ""
    correlation_id: str = field(default_factory=generate_contract_id)
    sequence_number: int = 1
    units: Dict[str, str] = field(default_factory=dict)
    coordinate_frame: Optional[str] = None
    signature: str = ""
    hash: str = ""

    @property
    def envelope(self):
        """Return self as the envelope - all contract fields are on BaseContract directly.
        Allows code using contract.envelope.field to access metadata fields."""
        return self

    def _canonical_payload_dict(self) -> Dict[str, Any]:
        """Return canonical dictionary representation excluding signature and hash."""
        data = asdict(self)
        data.pop("signature", None)
        data.pop("hash", None)
        return data

    def compute_hash(self) -> str:
        """Compute SHA-256 hash of canonical contract payload."""
        payload_dict = self._canonical_payload_dict()
        canonical_json = json.dumps(payload_dict, sort_keys=True, default=str)
        self.hash = hashlib.sha256(canonical_json.encode("utf-8")).hexdigest()
        return self.hash

    def sign(self, secret_key: str) -> str:
        """Sign the contract hash using HMAC-SHA256."""
        if not self.hash:
            self.compute_hash()
        mac = hmac.new(
            secret_key.encode("utf-8"),
            self.hash.encode("utf-8"),
            hashlib.sha256
        )
        self.signature = mac.hexdigest()
        return self.signature

    def verify_signature(self, secret_key: str) -> bool:
        """Verify HMAC-SHA256 signature against current contract content."""
        computed_hash = hashlib.sha256(
            json.dumps(self._canonical_payload_dict(), sort_keys=True, default=str).encode("utf-8")
        ).hexdigest()

        expected_mac = hmac.new(
            secret_key.encode("utf-8"),
            computed_hash.encode("utf-8"),
            hashlib.sha256
        ).hexdigest()

        return hmac.compare_digest(self.signature, expected_mac)

    def validate(self) -> bool:
        """Validate metadata and contract invariant rules.

        Subclasses should override and call super().validate().
        Raises ValueError if invalid.
        """
        if not self.contract_version:
            raise ValueError("contract_version is mandatory")
        if not self.schema_version:
            raise ValueError("schema_version is mandatory")
        if not self.contract_id:
            raise ValueError("contract_id is mandatory")
        if not self.producer:
            raise ValueError("producer is mandatory")
        if not self.consumer:
            raise ValueError("consumer is mandatory")
        if not self.correlation_id:
            raise ValueError("correlation_id is mandatory")
        if self.sequence_number < 0:
            raise ValueError("sequence_number must be non-negative")
        if self.timestamp <= 0:
            raise ValueError("timestamp must be positive")
        return True

    def to_dict(self) -> Dict[str, Any]:
        """Export contract dataclass to dictionary."""
        if not self.hash:
            self.compute_hash()
        return asdict(self)

    @classmethod
    def from_dict(cls, data: Dict[str, Any]) -> "BaseContract":
        """Instantiate contract from dictionary and run validation."""
        instance = cls(**data)
        instance.validate()
        return instance


