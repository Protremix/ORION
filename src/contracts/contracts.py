@dataclass
class BeliefState(BaseContract):
    """2. BeliefState Contract.

    Produced by State Plane, consumed by Cognitive Plane, Action Arbitration, Safety Enforcement.
    Provides estimated world state, object tracking, spatial pose, and covariance matrices.
    """
    state_revision: int = 0
    position: List[float] = field(default_factory=lambda: [0.0, 0.0, 0.0])
    orientation: List[float] = field(default_factory=lambda: [0.0, 0.0, 0.0, 1.0])
    velocity: Optional[List[float]] = field(default_factory=lambda: [0.0, 0.0, 0.0])
    objects: List[Dict[str, Any]] = field(default_factory=list)
    uncertainty: Dict[str, Any] = field(default_factory=lambda: {
        "position_covariance": [[0.01, 0.0, 0.0], [0.0, 0.01, 0.0], [0.0, 0.0, 0.01]],
        "orientation_covariance": [[0.01, 0.0, 0.0], [0.0, 0.01, 0.0], [0.0, 0.0, 0.01]],
        "classification_confidence": 0.95
    })
    staleness: int = 0  # nanoseconds
    sensor_health: Dict[str, str] = field(default_factory=dict)
    confidence: float = 1.0

    def __post_init__(self):
        if not self.producer:
            self.producer = Plane.STATE.value
        if not self.consumer:
            self.consumer = Plane.COGNITIVE.value
        if self.coordinate_frame is None:
            self.coordinate_frame = "world"

    def validate(self) -> bool:
        super().validate()
        if self.state_revision < 0:
            raise ValueError("BeliefState.state_revision must be non-negative")
        if len(self.position) != 3:
            raise ValueError("BeliefState.position must be a 3D vector [x, y, z]")
        if len(self.orientation) != 4:
            raise ValueError("BeliefState.orientation must be a 4D quaternion [x, y, z, w]")
        if not (0.0 <= self.confidence <= 1.0):
            raise ValueError(f"BeliefState.confidence ({self.confidence}) must be in [0.0, 1.0]")
        if self.staleness < 0:
            raise ValueError("BeliefState.staleness must be non-negative")
        return True


