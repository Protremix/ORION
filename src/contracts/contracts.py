"""ORION Phase 1 - Normative Data Contracts.

This module defines the 9 normative data contracts specified in the ORION
Architecture v0.5 baseline. All contracts inherit from `BaseContract` which
enforces standard metadata, cryptographic integrity (SHA-256 hashing and HMAC
signing), serialization, and validation.

Normative Contracts:
1. Observation - Sensor data and observation state.
2. BeliefState - Filtered world state estimate with covariance.
3. Goal - High-level task or objective specification.
4. ActionProposal - Candidate action generated by Cognitive Plane.
5. ActionAuthorization - Time-bounded, constrained execution lease.
6. ActionExecutionResult - Outcome and telemetry from Control Plane.
7. SafetyDecision - Overrides, halts, and blocks from Safety Enforcement.
8. AuditEvent - Immutable audit trail record with hash chain integrity.
9. MemoryWrite - Cognitive memory storage request.
"""

