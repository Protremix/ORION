@dataclass
class Observation(BaseContract):
    """1. Observation Contract.

    Produced by State Plane, consumed by Cognitive Plane and Action Arbitration.
    Encapsulates raw and preprocessed sensor data with confidence and latency telemetry.
    """
    sensor_id: str = "sensor_0"
    sensor_type: str = "camera"
    raw_data: Union[bytes, str, Dict[str, Any]] = field(default_factory=dict)
    processed_data: Optional[Dict[str, Any]] = None
    confidence: float = 1.0
    timestamp_sensor: int = field(default_factory=current_timestamp_ns)
    latency: int = 0  # nanoseconds
    uncertainty: Dict[str, Any] = field(default_factory=dict)

    def __post_init__(self):
        if not self.producer:
            self.producer = Plane.STATE.value
        if not self.consumer:
            self.consumer = Plane.COGNITIVE.value

    def validate(self) -> bool:
        super().validate()
        if not self.sensor_id:
            raise ValueError("Observation.sensor_id is mandatory")
        if not self.sensor_type:
            raise ValueError("Observation.sensor_type is mandatory")
        if not (0.0 <= self.confidence <= 1.0):
            raise ValueError(f"Observation.confidence ({self.confidence}) must be in [0.0, 1.0]")
        if self.timestamp_sensor <= 0:
            raise ValueError("Observation.timestamp_sensor must be positive")
        if self.latency < 0:
            raise ValueError("Observation.latency must be non-negative")
        return True


