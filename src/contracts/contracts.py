        super().validate()
        # Architecture v0.5 B.9 Rule: Writer restriction
        if self.producer != Plane.COGNITIVE.value:
            raise ValueError(f"MemoryWrite producer MUST be '{Plane.COGNITIVE.value}', got '{self.producer}'")
